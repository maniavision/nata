"""Writes supabase/functions/send-push/texts.ts from the app's .arb files, so
push notifications use the same words as the in-app list
(lib/l10n/notification_text.dart). Run again after changing those strings:

    python3 scripts/gen_push_texts.py
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
# event -> (title key, body key); must match notification_text.dart.
EVENTS = {
    "request_new": ("notifRequestNewTitle", "notifRequestNewBody"),
    "request_accepted": ("notifAcceptedTitle", "notifAcceptedBody"),
    "request_declined": ("notifDeclinedTitle", "notifDeclinedBody"),
    "request_expired_unanswered": ("notifExpiredTitle", "notifExpiredUnansweredBody"),
    "request_expired_unpaid": ("notifExpiredTitle", "notifExpiredUnpaidBody"),
    "request_expired_unpaid_traveler": ("notifExpiredTitle", "notifExpiredUnpaidTravelerBody"),
    "request_cancelled_by_traveler": ("notifCancelledTitle", "notifCancelledByTravelerBody"),
    "request_cancelled_by_sender": ("notifCancelledTitle", "notifCancelledBySenderBody"),
    "request_paid": ("notifPaidTitle", "notifPaidBody"),
    "item_picked_up": ("notifPickedUpTitle", "notifPickedUpBody"),
    "item_delivered": ("notifDeliveredTitle", "notifDeliveredBody"),
    "payout_paid": ("notifPayoutTitle", "notifPayoutBody"),
    "refund_sent": ("notifRefundTitle", "notifRefundBody"),
    "identity_verified": ("notifVerifiedTitle", "notifVerifiedBody"),
    "identity_rejected": ("notifRejectedTitle", "notifRejectedBody"),
    "problem_reported": ("notifProblemTitle", "notifProblemBody"),
    "message_new": ("notifMessageTitle", "notifMessageBody"),
    "message_photo": ("notifMessageTitle", "notifMessagePhotoBody"),
}

out = {}
for lang in ("en", "es", "fr"):
    arb = json.loads((ROOT / f"lib/l10n/app_{lang}.arb").read_text(encoding="utf-8"))
    out[lang] = {e: [arb[t], arb[b]] for e, (t, b) in EVENTS.items()}

ts = (
    "// Generated by scripts/gen_push_texts.py from lib/l10n/app_*.arb. Do not\n"
    "// edit by hand. Placeholders: {sender} {traveler} {route} {amount} {name} {message}.\n\n"
    "export const TEXTS: Record<string, Record<string, [string, string]>> =\n"
    + json.dumps(out, ensure_ascii=False, indent=2)
    + ";\n"
)
(ROOT / "supabase/functions/send-push/texts.ts").write_text(ts, encoding="utf-8")
print("wrote", sum(len(v) for v in out.values()), "texts")
